def get_activity_icon(activity_type: str) -> str:
    """الحصول على أيقونة النشاط"""
    return ACTIVITY_ICONS.get(activity_type, "📝")

def get_color(color_type: str) -> int:
    """الحصول على لون الـ embed"""
    return COLORS.get(color_type, COLORS["summary"])

def is_trackable_message(content: str, has_attachments: bool) -> bool:
    """تحديد ما إذا كانت الرسالة قابلة للتتبع"""
    if not TRACK_MESSAGES:
        return False
    
    return len(content) >= MIN_MESSAGE_LENGTH or has_attachments

def should_track_activity(activity_type: str) -> bool:
    """تحديد ما إذا كان النشاط قابل للتتبع"""
    tracking_map = {
        "join": TRACK_JOINS,
        "leave": TRACK_LEAVES,
        "message": TRACK_MESSAGES,
        "voice_join": TRACK_VOICE,
        "voice_leave": TRACK_VOICE,
        "game_start": TRACK_GAMES,
        "status_update": TRACK_STATUS_UPDATES
    }
    
    return tracking_map.get(activity_type, False)